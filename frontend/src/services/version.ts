import { Modal, message } from 'ant-design-vue'
import { reactive } from 'vue'
import {
  CheckUpdate,
  GetAppVersion,
  GetUpdateState,
  InstallUpdate,
  SetUpdateChannel,
  StartUpdateDownload,
} from '../../wailsjs/go/main/App'
import { BrowserOpenURL, EventsOn } from '../../wailsjs/runtime/runtime'
import type { updater } from '../../wailsjs/go/models'
import { useAppStore } from '../stores/app'

/**
 * True when the app is built for App Store distribution (VITE_APPSTORE_BUILD=true).
 * Version check UI and auto-check are disabled in this build.
 */
export const isAppStoreBuild = import.meta.env.VITE_APPSTORE_BUILD === 'true'

// Types generated by Wails from internal/updater.
export type UpdateAsset = updater.Asset
export type UpdateRelease = updater.Release
export type UpdateState = updater.State
export type InstallResult = updater.InstallResult

/** Shared reactive state, updated by the update:state event. */
export const updateStore = reactive<{ state: UpdateState | null }>({ state: null })

let bindOnce = false
let downloadToast: (() => void) | null = null

function closeDownloadToast() {
  if (downloadToast) {
    downloadToast()
    downloadToast = null
  }
}

/** Subscribe once to backend progress events and load the initial state. */
export function bindUpdateEvents(): void {
  if (bindOnce) return
  bindOnce = true
  EventsOn('update:state', (state: UpdateState) => {
    updateStore.state = state
    const appStore = useAppStore()
    if (state.state === 'ready') {
      closeDownloadToast()
      message.success(appStore.t('settings.version.updateReady'))
    } else if (state.state === 'failed') {
      closeDownloadToast()
      message.error(state.error || appStore.t('settings.version.updateFailed'))
    }
  })
  GetUpdateState()
    .then((state) => {
      updateStore.state = state
    })
    .catch(() => {
      // The backend is available only in the GUI; ignore in browser tests.
    })
}

// Cache for app version
let cachedAppVersion: string | null = null

/** Get app version from backend (cached). */
export async function getAppVersion(): Promise<string> {
  if (cachedAppVersion) {
    return cachedAppVersion
  }
  cachedAppVersion = await GetAppVersion()
  return cachedAppVersion
}

export interface VersionCheckOptions {
  /** Whether to show message when already on latest version */
  showLatestMessage?: boolean
  /** Whether to show error message on failure */
  showErrorMessage?: boolean
}

/**
 * Check for a new version and offer to download it. The actual download runs in
 * the backend and reports progress through update:state.
 */
export async function checkVersionAndPrompt(options: VersionCheckOptions = {}): Promise<boolean> {
  const { showLatestMessage = false, showErrorMessage = false } = options
  const appStore = useAppStore()
  bindUpdateEvents()

  try {
    const state = await CheckUpdate('latest')
    updateStore.state = state

    if (state.state === 'up-to-date') {
      if (showLatestMessage) {
        message.success(appStore.t('settings.version.latestVersion'))
      }
      return false
    }
    if (state.state === 'failed') {
      throw new Error(state.error || 'check failed')
    }
    const release = state.release
    if (!release) {
      return false
    }
    if (!state.asset) {
      Modal.confirm({
        title: appStore.t('settings.version.updateAvailable'),
        content: appStore.t('settings.version.updateConfirm', { version: release.version }),
        okText: appStore.t('common.yes'),
        cancelText: appStore.t('common.no'),
        onOk() {
          BrowserOpenURL(release.url)
        },
      })
      return true
    }
    Modal.confirm({
      title: appStore.t('settings.version.updateAvailable'),
      content: appStore.t('settings.version.downloadConfirm', {
        version: release.version,
        summary: release.summary || '',
      }),
      okText: appStore.t('settings.version.downloadUpdate'),
      cancelText: appStore.t('common.no'),
      onOk() {
        closeDownloadToast()
        downloadToast = message.loading({
          content: appStore.t('settings.version.downloading'),
          duration: 0,
        }) as unknown as () => void
        return StartUpdateDownload().catch((err) => {
          closeDownloadToast()
          message.error(String(err))
        })
      },
    })
    return true
  } catch (e) {
    console.error('Version check failed:', e)
    if (showErrorMessage) {
      message.error(appStore.t('settings.version.checkFailed'))
    }
    return false
  }
}

/** Start the background download (progress arrives through updateStore). */
export async function downloadUpdate(): Promise<void> {
  bindUpdateEvents()
  await StartUpdateDownload()
}

/** Install the downloaded version; the app restarts when it succeeds. */
export async function installUpdate(): Promise<InstallResult> {
  bindUpdateEvents()
  return InstallUpdate()
}

/** Switch between stable and beta channels. */
export async function setUpdateChannel(channel: 'latest' | 'stable' | 'beta'): Promise<UpdateState> {
  bindUpdateEvents()
  const state = await SetUpdateChannel(channel)
  updateStore.state = state
  return state
}

/** Auto check version after a delay (used on app startup). */
export function autoCheckVersion(delayMs: number = 5000): void {
  bindUpdateEvents()
  setTimeout(() => {
    checkVersionAndPrompt({ showLatestMessage: false, showErrorMessage: false })
  }, delayMs)
}
